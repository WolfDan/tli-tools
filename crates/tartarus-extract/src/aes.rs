const RCON: [u8; 11] = [
    0x00, 0x01, 0x02, 0x04, 0x08, 0x10, 0x20, 0x40, 0x80, 0x1B, 0x36,
];

#[inline]
const fn gmul(mut a: u8, mut b: u8) -> u8 {
    let mut p = 0u8;
    let mut i = 0;
    while i < 8 {
        if (b & 1) != 0 {
            p ^= a;
        }
        let hi = a & 0x80;
        a <<= 1;
        if hi != 0 {
            a ^= 0x1B;
        }
        b >>= 1;
        i += 1;
    }
    p
}

fn decrypt_aes256_ecb_soft(buf: &mut [u8], key: &[u8; 32]) {
    let mut w = [[0u8; 4]; 60];
    for i in 0..8 {
        w[i] = [key[i * 4], key[i * 4 + 1], key[i * 4 + 2], key[i * 4 + 3]];
    }
    for i in 8..60 {
        let mut temp = w[i - 1];
        if i % 8 == 0 {
            temp = [
                SBOX[temp[1] as usize] ^ RCON[i / 8],
                SBOX[temp[2] as usize],
                SBOX[temp[3] as usize],
                SBOX[temp[0] as usize],
            ];
        } else if i % 8 == 4 {
            temp = [
                SBOX[temp[0] as usize],
                SBOX[temp[1] as usize],
                SBOX[temp[2] as usize],
                SBOX[temp[3] as usize],
            ];
        }
        let prev = w[i - 8];
        w[i] = [
            prev[0] ^ temp[0],
            prev[1] ^ temp[1],
            prev[2] ^ temp[2],
            prev[3] ^ temp[3],
        ];
    }

    let mut rks = [[0u8; 16]; 15];
    for r in 0..15 {
        for c in 0..4 {
            rks[r][c * 4..c * 4 + 4].copy_from_slice(&w[r * 4 + c]);
        }
    }

    for block in buf.as_chunks_mut::<16>().0 {
        let mut s = [0u8; 16];
        for i in 0..16 {
            s[i] = block[i] ^ rks[14][i];
        }
        for r in (1..14).rev() {
            s = [
                s[0], s[13], s[10], s[7], s[4], s[1], s[14], s[11], s[8], s[5], s[2], s[15], s[12],
                s[9], s[6], s[3],
            ];
            for i in 0..16 {
                s[i] = INV_SBOX[s[i] as usize] ^ rks[r][i];
            }
            let mut ns = [0u8; 16];
            for c in 0..4 {
                let idx = c * 4;
                let (s0, s1, s2, s3) = (s[idx], s[idx + 1], s[idx + 2], s[idx + 3]);
                ns[idx] = gmul(s0, 14) ^ gmul(s1, 11) ^ gmul(s2, 13) ^ gmul(s3, 9);
                ns[idx + 1] = gmul(s0, 9) ^ gmul(s1, 14) ^ gmul(s2, 11) ^ gmul(s3, 13);
                ns[idx + 2] = gmul(s0, 13) ^ gmul(s1, 9) ^ gmul(s2, 14) ^ gmul(s3, 11);
                ns[idx + 3] = gmul(s0, 11) ^ gmul(s1, 13) ^ gmul(s2, 9) ^ gmul(s3, 14);
            }
            s = ns;
        }
        s = [
            s[0], s[13], s[10], s[7], s[4], s[1], s[14], s[11], s[8], s[5], s[2], s[15], s[12],
            s[9], s[6], s[3],
        ];
        for i in 0..16 {
            block[i] = INV_SBOX[s[i] as usize] ^ rks[0][i];
        }
    }
}
