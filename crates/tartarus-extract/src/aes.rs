pub fn parse_hex_key(s: &str) -> Result<[u8; 32], String> {
    let clean = s
        .trim()
        .strip_prefix("0x")
        .or_else(|| s.trim().strip_prefix("0X"))
        .unwrap_or(s.trim());
    if clean.len() != 64 {
        return Err(format!(
            "AES-256 hex key must be 64 hex chars (32 bytes), got {} chars",
            clean.len()
        ));
    }
    let mut out = [0u8; 32];
    for i in 0..32 {
        out[i] = u8::from_str_radix(&clean[i * 2..i * 2 + 2], 16)
            .map_err(|e| format!("Invalid hex at byte {i}: {e}"))?;
    }
    Ok(out)
}

pub fn parse_aes_key_hex(s: &str) -> Result<[u8; 32], String> {
    parse_hex_key(s)
}

/// Decrypts `buf` in-place using AES-256-ECB. `buf.len()` is rounded down to a multiple of 16 bytes.
#[inline]
pub fn decrypt_aes256_ecb_in_place(buf: &mut [u8], key: &[u8; 32]) {
    #[cfg(target_arch = "x86_64")]
    {
        if std::is_x86_feature_detected!("aes") && std::is_x86_feature_detected!("sse4.1") {
            // SAFETY: CPU feature detection confirmed `aes` and `sse4.1` are available.
            unsafe {
                decrypt_aes256_ecb_aesni(buf, key);
            }
            return;
        }
    }
    decrypt_aes256_ecb_soft(buf, key);
}

#[cfg(target_arch = "x86_64")]
#[target_feature(enable = "aes,sse4.1")]
unsafe fn key_expand_step(
    k1: &mut core::arch::x86_64::__m128i,
    k2: &mut core::arch::x86_64::__m128i,
    assist1: core::arch::x86_64::__m128i,
) {
    use core::arch::x86_64::*;
    let mut t1 = *k1;
    let mut t2 = *k2;
    let rcon = _mm_shuffle_epi32(assist1, 0xFF);
    let mut t3 = _mm_slli_si128(t1, 4);
    t1 = _mm_xor_si128(t1, t3);
    t3 = _mm_slli_si128(t3, 4);
    t1 = _mm_xor_si128(t1, t3);
    t3 = _mm_slli_si128(t3, 4);
    t1 = _mm_xor_si128(t1, t3);
    t1 = _mm_xor_si128(t1, rcon);
    *k1 = t1;

    t3 = _mm_aeskeygenassist_si128(t1, 0x00);
    t3 = _mm_shuffle_epi32(t3, 0xAA);
    t1 = _mm_slli_si128(t2, 4);
    t2 = _mm_xor_si128(t2, t1);
    t1 = _mm_slli_si128(t1, 4);
    t2 = _mm_xor_si128(t2, t1);
    t1 = _mm_slli_si128(t1, 4);
    t2 = _mm_xor_si128(t2, t1);
    t2 = _mm_xor_si128(t2, t3);
    *k2 = t2;
}

#[cfg(target_arch = "x86_64")]
#[target_feature(enable = "aes,sse4.1")]
unsafe fn decrypt_aes256_ecb_aesni(buf: &mut [u8], key: &[u8; 32]) {
    use core::arch::x86_64::*;
    unsafe {
        let mut ek = [_mm_setzero_si128(); 15];
        let mut dk = [_mm_setzero_si128(); 15];
        let mut k1 = _mm_loadu_si128(key.as_ptr().cast::<__m128i>());
        let mut k2 = _mm_loadu_si128(key.as_ptr().add(16).cast::<__m128i>());
        ek[0] = k1;
        ek[1] = k2;

        let a1 = _mm_aeskeygenassist_si128(k2, 0x01);
        key_expand_step(&mut k1, &mut k2, a1);
        ek[2] = k1;
        ek[3] = k2;
        let a2 = _mm_aeskeygenassist_si128(k2, 0x02);
        key_expand_step(&mut k1, &mut k2, a2);
        ek[4] = k1;
        ek[5] = k2;
        let a4 = _mm_aeskeygenassist_si128(k2, 0x04);
        key_expand_step(&mut k1, &mut k2, a4);
        ek[6] = k1;
        ek[7] = k2;
        let a8 = _mm_aeskeygenassist_si128(k2, 0x08);
        key_expand_step(&mut k1, &mut k2, a8);
        ek[8] = k1;
        ek[9] = k2;
        let a10 = _mm_aeskeygenassist_si128(k2, 0x10);
        key_expand_step(&mut k1, &mut k2, a10);
        ek[10] = k1;
        ek[11] = k2;
        let a20 = _mm_aeskeygenassist_si128(k2, 0x20);
        key_expand_step(&mut k1, &mut k2, a20);
        ek[12] = k1;
        ek[13] = k2;
        let a40 = _mm_aeskeygenassist_si128(k2, 0x40);
        key_expand_step(&mut k1, &mut k2, a40);
        ek[14] = k1;

        dk[0] = ek[14];
        for i in 1..14 {
            dk[i] = _mm_aesimc_si128(ek[14 - i]);
        }
        dk[14] = ek[0];

        let blocks = buf.len() / 16;
        let ptr = buf.as_mut_ptr().cast::<__m128i>();
        for i in 0..blocks {
            let p = ptr.add(i);
            let mut b = _mm_loadu_si128(p);
            b = _mm_xor_si128(b, dk[0]);
            for r in 1..14 {
                b = _mm_aesdec_si128(b, dk[r]);
            }
            b = _mm_aesdeclast_si128(b, dk[14]);
            _mm_storeu_si128(p, b);
        }
    }
}

